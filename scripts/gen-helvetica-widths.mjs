// Generates src/lib/labels/helvetica-widths.ts from pdf-lib's standard font metrics.
// Run: node scripts/gen-helvetica-widths.mjs
import { writeFileSync } from 'node:fs'
import { Encodings, Font, FontNames } from '@pdf-lib/standard-fonts'

const table = (name) => {
  const font = Font.load(name)
  const widths = {}
  for (let cp = 32; cp <= 0x2122; cp++) {
    let glyph
    try {
      glyph = Encodings.WinAnsi.encodeUnicodeCodePoint(cp)
    } catch {
      continue
    }
    const w = font.getWidthOfGlyph(glyph.name)
    if (w !== undefined) widths[cp] = w
  }
  return widths
}

const regular = table(FontNames.Helvetica)
const bold = table(FontNames.HelveticaBold)
const fmt = (o) => JSON.stringify(o).replace(/"(\d+)":/g, '$1:')
writeFileSync(
  'src/lib/labels/helvetica-widths.ts',
  `// Generated by scripts/gen-helvetica-widths.mjs from the Adobe Helvetica metrics in pdf-lib.
// Glyph advance widths in 1/1000 em, keyed by Unicode code point (the WinAnsi character set).
// Characters missing here can't be drawn with the PDF's standard fonts.
export const HELVETICA: Record<number, number> = ${fmt(regular)}
export const HELVETICA_BOLD: Record<number, number> = ${fmt(bold)}
`,
)
